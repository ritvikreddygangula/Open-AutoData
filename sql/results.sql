CREATE OR REPLACE VIEW OPENAUTODATA.PUBLIC.V_RESULTS_ROWS AS
WITH runs AS (
    SELECT ARM, RUN_ID, MAX(CREATED_AT) AS LAST_AT
    FROM OPENAUTODATA.PUBLIC.OPENAUTODATA_TRAJECTORIES
    WHERE ARM IN ('loop', 'baseline')
    GROUP BY ARM, RUN_ID
),
latest AS (
    SELECT ARM, RUN_ID
    FROM runs
    QUALIFY ROW_NUMBER() OVER (PARTITION BY ARM ORDER BY LAST_AT DESC) = 1
)
SELECT
    t.*,
    t.STRONG_SCORE - t.WEAK_SCORE AS GAP,
    COALESCE(t.FAIL_REASON ILIKE 'error:%', FALSE) AS IS_ERROR,
    ROW_NUMBER() OVER (PARTITION BY t.ARM, t.CHUNK_ID ORDER BY t.ROUND_NUM DESC, t.CREATED_AT DESC) = 1 AS IS_FINAL_ROUND
FROM OPENAUTODATA.PUBLIC.OPENAUTODATA_TRAJECTORIES t
JOIN latest l ON t.ARM = l.ARM AND t.RUN_ID = l.RUN_ID;

CREATE OR REPLACE VIEW OPENAUTODATA.PUBLIC.V_RESULTS_SUMMARY AS
SELECT 1 AS ORD, 'baseline (one shot, no checks)' AS DATASET,
    COUNT(*) AS N_QUESTIONS, COUNT(WEAK_SCORE) AS N_SCORED,
    ROUND(AVG(WEAK_SCORE), 1) AS AVG_WEAK, ROUND(AVG(STRONG_SCORE), 1) AS AVG_STRONG, ROUND(AVG(GAP), 1) AS AVG_GAP,
    ROUND(100 * AVG(IFF(WEAK_SCORE <= 65 AND STRONG_SCORE >= 60 AND GAP >= 20, 1, 0)), 1) AS PCT_PASS_CORE_GATE
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE ARM = 'baseline' AND NOT IS_ERROR
UNION ALL
SELECT 2, 'loop round 1 (before feedback)',
    COUNT(*), COUNT(WEAK_SCORE),
    ROUND(AVG(WEAK_SCORE), 1), ROUND(AVG(STRONG_SCORE), 1), ROUND(AVG(GAP), 1),
    ROUND(100 * AVG(IFF(WEAK_SCORE <= 65 AND STRONG_SCORE >= 60 AND GAP >= 20, 1, 0)), 1)
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE ARM = 'loop' AND ROUND_NUM = 1 AND NOT IS_ERROR
UNION ALL
SELECT 3, 'loop accepted (final dataset)',
    COUNT(*), COUNT(WEAK_SCORE),
    ROUND(AVG(WEAK_SCORE), 1), ROUND(AVG(STRONG_SCORE), 1), ROUND(AVG(GAP), 1),
    ROUND(100 * AVG(IFF(WEAK_SCORE <= 65 AND STRONG_SCORE >= 60 AND GAP >= 20, 1, 0)), 1)
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE ARM = 'loop' AND STATUS = 'ACCEPTED';

SELECT RUN_ID, ARM, STATUS, COUNT(*) AS N_ROWS, MAX(CREATED_AT) AS LAST_WRITE
FROM OPENAUTODATA.PUBLIC.OPENAUTODATA_TRAJECTORIES
GROUP BY RUN_ID, ARM, STATUS
ORDER BY LAST_WRITE DESC;

SELECT RUN_ID, ARM, COUNT(*) AS N_ACCEPTED
FROM OPENAUTODATA.PUBLIC.OPENAUTODATA_ACCEPTED_SET
GROUP BY RUN_ID, ARM;

SELECT * FROM OPENAUTODATA.PUBLIC.V_RESULTS_SUMMARY ORDER BY ORD;

SELECT
    COUNT(*) AS CHUNKS,
    SUM(IFF(STATUS = 'ACCEPTED', 1, 0)) AS ACCEPTED,
    SUM(IFF(STATUS = 'REJECTED' AND NOT IS_ERROR, 1, 0)) AS REJECTED_QUALITY,
    SUM(IFF(IS_ERROR, 1, 0)) AS REJECTED_ERROR,
    ROUND(100 * AVG(IFF(STATUS = 'ACCEPTED', 1, 0)), 1) AS PCT_ACCEPTED,
    ROUND(AVG(IFF(STATUS = 'ACCEPTED', ROUND_NUM, NULL)), 2) AS AVG_ROUNDS_TO_ACCEPT
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE ARM = 'loop' AND IS_FINAL_ROUND;

SELECT FAILURE_MODE, COUNT(*) AS N_ROUNDS
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE ARM = 'loop' AND FAILURE_MODE IS NOT NULL
GROUP BY FAILURE_MODE
ORDER BY N_ROUNDS DESC;

SELECT ROUND_NUM, COUNT(*) AS N_ROUNDS,
    ROUND(AVG(WEAK_SCORE), 1) AS AVG_WEAK, ROUND(AVG(STRONG_SCORE), 1) AS AVG_STRONG, ROUND(AVG(GAP), 1) AS AVG_GAP
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE ARM = 'loop' AND NOT IS_ERROR
GROUP BY ROUND_NUM
ORDER BY ROUND_NUM;

SELECT CHUNK_ID, ROUND_NUM AS ACCEPTED_AT_ROUND, WEAK_SCORE, STRONG_SCORE, GAP, QUESTION
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE ARM = 'loop' AND STATUS = 'ACCEPTED' AND ROUND_NUM >= 2
ORDER BY ROUND_NUM DESC, GAP DESC;

SET DEMO_CHUNK = 4;

SELECT ROUND_NUM, STATUS, FAILURE_MODE, WEAK_SCORE, STRONG_SCORE, GAP, QUESTION, FAIL_REASON, JUDGE_FEEDBACK
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE ARM = 'loop' AND CHUNK_ID = $DEMO_CHUNK
ORDER BY ROUND_NUM;

SELECT CHUNK_ID, QUESTION_TYPE, CONTEXT, QUESTION, REFERENCE_ANSWER, RUBRIC, WEAK_SCORE, STRONG_SCORE, GAP
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE ARM = 'loop' AND STATUS = 'ACCEPTED'
ORDER BY GAP DESC;

SELECT ARM, CHUNK_ID, ROUND_NUM, FAIL_REASON
FROM OPENAUTODATA.PUBLIC.V_RESULTS_ROWS
WHERE IS_ERROR
ORDER BY ARM, CHUNK_ID;
